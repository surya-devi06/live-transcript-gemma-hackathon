"""Export utility functions for transcripts, notes, and study guides."""

import json
from typing import Dict, List, Optional, Any
from datetime import datetime


class ExportManager:
    """Handles structured exporting to TXT, Markdown, and JSON."""

    @staticmethod
    def export_as_txt(transcript_text: str, timestamped_text: Optional[str] = None) -> str:
        """Generate formatted plain text transcript."""
        header = (
            "=====================================================\n"
            "LIVE TRANSCRIPT AI - EXPORTED TRANSCRIPT\n"
            f"Generated: {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')}\n"
            "=====================================================\n\n"
        )
        if timestamped_text:
            return header + "TIMESTAMPED TRANSCRIPT:\n" + timestamped_text + "\n\nRAW TEXT:\n" + transcript_text
        return header + transcript_text

    @staticmethod
    def export_as_markdown(
        title: str,
        notes_markdown: str,
        transcript_text: Optional[str] = None,
        metadata: Optional[Dict[str, Any]] = None,
    ) -> str:
        """Generate structured Markdown document for study notes."""
        md_lines = [
            f"# {title}",
            f"*Generated by Live Transcript AI (Powered by Google Gemma 4) on {datetime.utcnow().strftime('%Y-%m-%d %H:%M UTC')}*\n",
            "---",
            notes_markdown,
            "\n---",
        ]
        if metadata:
            md_lines.append("\n### ⚙️ Session Details")
            for k, v in metadata.items():
                md_lines.append(f"- **{k.replace('_', ' ').title()}**: {v}")

        if transcript_text:
            md_lines.append("\n### 📜 Full Verbatim Transcript")
            md_lines.append(f"> {transcript_text}")

        return "\n".join(md_lines)

    @staticmethod
    def export_as_json(
        transcript_result: Dict[str, Any],
        learning_notes: str,
        qa_history: Optional[List[Dict[str, Any]]] = None,
    ) -> str:
        """Generate complete session JSON export."""
        payload = {
            "application": "Live Transcript AI",
            "exported_at": datetime.utcnow().isoformat(),
            "transcript": transcript_result,
            "learning_notes": learning_notes,
            "qa_history": qa_history or [],
        }
        return json.dumps(payload, indent=2, ensure_ascii=False)
